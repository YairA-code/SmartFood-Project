// מספרי E שכתובים ברכיב: E500, E-500, E500ii, 471-E
function eNumbers(s) {
  const out = [];
  for (const m of s.matchAll(/E\s?-?\s?(\d{3,4})([a-z]{0,3})|(\d{3,4})\s?-\s?E/gi)) {
    const num = m[1] || m[3], sub = (m[2] || '').toLowerCase();
    const id = byE.get(eKey(num + sub)) || byE.get(eKey(num + sub.replace(/i+$/, ''))) || byE.get(eKey(num));
    if (id) out.push(id);
  }
  return out;
}
// חומרים מוכרים לפי שם
function named(s) {
  let rest = ' ' + norm(s) + ' ', out = [];
  for (const [a, id] of aliases) {
    if (a.length < 3 && !/^[A-Z]/.test(a)) continue;
    if (rest.includes(a)) { out.push(id); rest = rest.split(a).join(' | '); }
  }
  return out;
}
const baseOf = s => norm(s).replace(/\s*\(.*$/s, '').replace(/:.*$/, '').trim();

// רכיב מוצר → ערכי המילון שהוא שייך אליהם
function resolve(raw) {
  const full = norm(raw);
  const exact = aliases.find(([a]) => a === full);
  if (exact) return [exact[1]];
  if (byE.has(eKey(full)) && /^E/i.test(full)) return [byE.get(eKey(full))];
  const base = baseOf(raw), es = eNumbers(full);
  const bareBase = base.replace(/E\s?-?\s?\d{3,4}[a-z]*/gi, '').trim();
  const g = groupWord.get(base) || groupWord.get(bareBase);
  if (g) {
    const [gid, mode] = g;
    if (mode === 'class') return uniq([gid, ...es]);
    const found = uniq([...es, ...named(full.slice(base.length))]);
    return found.length ? found : [gid];
  }
  const inBase = named(base);
  if (inBase.length && !sameAs.has(base)) return uniq([...inBase, ...es, ...named(full.slice(base.length))]);
  const food = sameAs.get(base) || sameAs.get(full) || base || full;
  if (!terms.has(food)) {
    const src = INGREDIENTS[food] || INGREDIENTS[full] || INGREDIENTS[raw] || {};
    add({ id: food, name: food, e: [], type: src.type || 'רכיב', risk: src.risk || S, nova: src.nova || W, reason: src.reason || '', aliases: [] });
  }
  return uniq([food, ...es, ...named(full.slice(base.length))]);
}
const uniq = a => [...new Set(a)];

// לכל רכיב במילון המקורי: לאילו ערכים הוא שייך
const keyTerms = new Map();
for (const k of Object.keys(INGREDIENTS)) {
  const ids = resolve(k);
  keyTerms.set(k, ids);
  ids.forEach(id => terms.get(id).keys.push(k));
}
// ערך מצרך: עדיף ההסבר של הצורה הפשוטה ביותר
for (const t of terms.values()) {
  if (t.reason) continue;
  const k = t.keys.slice().sort((a, b) => a.length - b.length)[0];
  if (k) Object.assign(t, { type: INGREDIENTS[k].type, risk: INGREDIENTS[k].risk, nova: INGREDIENTS[k].nova, reason: INGREDIENTS[k].reason });
}

export function termsOf(raw) {
  const k = INGREDIENTS[raw] ? raw : canonicalName(raw);
  return (keyTerms.get(k) || resolve(k)).map(id => terms.get(id));
}

export function attachProducts(products) {
  terms.forEach(t => t.products.clear());
  products.forEach(p => p.ingredients.forEach(i => termsOf(i).forEach(t => t.products.add(p))));
}

export const allTerms = () => [...terms.values()].filter(t => t.products.size);
export const getTerm = id => terms.get(id) || null;

// מציאת ערך לפי מזהה, שם, מספר E או רכיב כפי שכתוב בתווית
export function findTerms(q) {
  const s = String(q).trim();
  if (terms.has(s)) return [terms.get(s)];
  if (/^E\s?-?\d/i.test(s) && byE.has(eKey(s.replace(/[\s-]/g, '')))) return [terms.get(byE.get(eKey(s.replace(/[\s-]/g, ''))))];
  const t = termsOf(s).filter(Boolean);
  return t;
}

