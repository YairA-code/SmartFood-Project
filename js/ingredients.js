// הסרת אחוזים מהשם, כדי ש"בוטנים טחונים (54%)" יתאים ל"בוטנים טחונים"
export function canonicalName(raw) {
  return String(raw)
    .replace(/\s*\((\d+(\.\d+)?)%\)\s*/g, ' ')
    .replace(/\s*\((מכיל )?גלוטן( חיטה| מחיטה)?\)\s*/g, ' ')
    .replace(/\s*\(מכיל גלוטן( חיטה| מחיטה| ממקור חיטה)?\)\s*/g, ' ')
    .replace(/\s*\((מכיל )?גלוטן( חיטה| מחיטה| ממקור חיטה)?\)\s*/g, ' ')
    .replace(/\s+([,)\]])/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

export function getIngredient(raw) {
  const name = String(raw).trim();
  return INGREDIENTS[name] || INGREDIENTS[canonicalName(name)] || null;
}
